/** The phone's primary navigation, where a thumb is; above 640px the same five sit in the top bar. */
export function TabBar({ variant }: { variant: 'bottom' | 'top' }) {
	const pathname = usePathname();
	return (
		<nav className={variant === 'bottom' ? 'tabbar' : 'topnav'} aria-label="Areas">
			{tabs.map((tab) => (
				<Link key={tab.href} href={tab.href} className={variant === 'bottom' ? 'tabbar__tab' : 'topnav__link'} aria-current={here(pathname, tab.href) ? 'page' : undefined}>
					{variant === 'bottom' ? (
						<svg className="tabbar__mark" viewBox="0 0 24 24" width="22" height="22" fill="none" stroke="currentColor" strokeWidth="2" strokeLinecap="round" strokeLinejoin="round" aria-hidden="true">{marks[tab.label]}</svg>
					) : null}
					<span className="tabbar__label">{tab.label}</span>
				</Link>
			))}
		</nav>
	);
}
